use std::path::PathBuf;
use std::process::Command;

use crate::profile::BoardProfile;
use crate::HilError;

pub fn vivado_tcl(profile: &BoardProfile, addr: u32, write: Option<u32>) -> String {
    let action = match write {
        Some(value) => format!(
            "create_hw_axi_txn wr -type write -address {addr:#010x} -data {{{value:08x}}} -force\nrun_hw_axi wr"
        ),
        None => format!(
            "create_hw_axi_txn rd -type read -address {addr:#010x} -force\nrun_hw_axi rd\nputs \"OPENMAT_REG [get_property DATA rd]\""
        ),
    };
    format!(
        r#"# Generated by openmat for {name}
open_hw_manager
connect_hw_server -url {server}
open_hw_target
set dev [lindex [get_hw_devices {device}*] 0]
current_hw_device $dev
refresh_hw_device -update_hw_probes false $dev
{action}
close_hw_target
"#,
        name = profile.name,
        server = profile.jtag_hw_server,
        device = profile.jtag_device,
        action = action,
    )
}

pub fn run_vivado(tcl: &str) -> Result<String, HilError> {
    let program = vivado_program()?;
    let file = tempfile_path();
    std::fs::write(&file, tcl).map_err(|err| HilError::new(format!("cannot write tcl: {err}")))?;
    let output = Command::new(&program)
        .args(["-mode", "batch", "-source"])
        .arg(&file)
        .output()
        .map_err(|err| HilError::new(format!("failed to start {}: {err}", program.display())))?;
    let _ = std::fs::remove_file(&file);
    let stdout = String::from_utf8_lossy(&output.stdout);
    let stderr = String::from_utf8_lossy(&output.stderr);
    if !output.status.success() {
        return Err(HilError::new(format!(
            "Vivado exited with {}: {stderr}{stdout}",
            output.status
        )));
    }
    Ok(format!("{stdout}{stderr}"))
}

pub fn parse_reg_read(text: &str) -> Result<u32, HilError> {
    for line in text.lines() {
        if let Some(rest) = line.trim().strip_prefix("OPENMAT_REG") {
            let token = rest.trim().trim_start_matches("0x");
            return u32::from_str_radix(token, 16)
                .map_err(|_| HilError::new(format!("cannot parse JTAG data '{rest}'")));
        }
    }
    Err(HilError::new(
        "Vivado output did not contain an OPENMAT_REG line",
    ))
}

fn vivado_program() -> Result<PathBuf, HilError> {
    if let Ok(path) = std::env::var("OPENMAT_VIVADO") {
        let path = PathBuf::from(path);
        if path.is_file() {
            return Ok(path);
        }
        return Err(HilError::new(format!(
            "OPENMAT_VIVADO does not point at Vivado ({})",
            path.display()
        )));
    }
    if which("vivado") {
        return Ok(PathBuf::from("vivado"));
    }
    Err(HilError::new(
        "Vivado was not found. Set OPENMAT_VIVADO to the vivado executable, or use hil.open('loopback') / Ethernet.",
    ))
}

fn which(name: &str) -> bool {
    Command::new("which")
        .arg(name)
        .output()
        .map(|out| out.status.success())
        .unwrap_or(false)
}

fn tempfile_path() -> PathBuf {
    let mut path = std::env::temp_dir();
    path.push(format!("openmat-jtag-{}.tcl", std::process::id()));
    path
}

